"""Tests for nonlinear GW emission from a chaotically-rotating cylinder.

Run from this directory:  python -m pytest test_gw_emission.py -q
(Evolutions are moderately expensive; grids are kept small.)
"""

import numpy as np

from nonlinear_gw_emission import emit, cross_polarization_scaling
from deep_tests import correlation_dimension_scalar


def test_radiated_omega_reconstructs_attractor_and_psi_is_folded():
    """The radiated twist omega reconstructs the Lorenz attractor (D2 ~ 2);
    the nonlinearly-generated psi has LOWER D2 (the omega^2 source folds lobes)."""
    out = emit(eps=0.05, r_out=45.0, n=2000, t_max=75.0, r_detector=16.0)
    d2_om = correlation_dimension_scalar(out["omega_det"], m=5)["D2"]
    d2_psi = correlation_dimension_scalar(out["psi_det"], m=5)["D2"]
    assert 1.6 < d2_om < 2.7                 # radiated twist carries the attractor
    assert out["max_psi_det"] > 1e-3          # psi is genuinely generated (nonlinear)
    assert d2_psi < d2_om                     # quadratic source folds -> lower dimension


def test_nonlinear_cross_polarization_scaling():
    """psi is generated by the omega^2 source: max|psi| ~ A^2, so psi/omega ~ A
    (roughly doubles when the drive amplitude doubles)."""
    rows = cross_polarization_scaling(amps=(0.02, 0.04), r_out=40.0, n=1600,
                                      t_max=45.0, r_detector=14.0)
    r0, r1 = rows[0], rows[1]
    assert r1["max_psi"] > r0["max_psi"]                       # grows with amplitude
    assert r1["ratio_psi_over_omega"] > 1.4 * r0["ratio_psi_over_omega"]  # ~ linear in A


def test_radiation_is_causal_and_bounded():
    out = emit(eps=0.04, r_out=40.0, n=1600, t_max=45.0, r_detector=14.0)
    assert np.all(np.isfinite(out["omega_det"]))
    assert np.all(np.isfinite(out["psi_det"]))
    assert out["max_omega_det"] < 10.0
